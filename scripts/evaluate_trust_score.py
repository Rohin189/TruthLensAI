"""Phase 10: compare the interim trust score with the claim-based score on the Phase 8 answers.

No Qwen needed: claim verdicts come from data/eval/verification_phase8.jsonl (Phase 9), and
query-source similarities are recomputed with the embedder (the val items store none).
The reference labels are the Phase 9 manual adjudication (docs/phase9_verification_findings.md).

Usage: python scripts\\evaluate_trust_score.py
"""
import json
import sys
from pathlib import Path
from statistics import mean

sys.path.append(str(Path(__file__).resolve().parent.parent))

import numpy as np

from app.embeddings.embedder import embed_query, embed_texts
from app.trust_score.trust_score import compute_claim_trust_score, compute_trust_score
from app.verification.phase8_audit import VERIFICATION_PATH, load_items

OUT_PATH = Path("data/eval/trust_scores_phase8.jsonl")
REPORT_PATH = Path("docs/evaluation_trust_score.md")

# answers with at least one claim confirmed unsupported by hand (Phase 9 adjudication, Section 4.2)
CONFIRMED_UNSUPPORTED = {("base", "q1"), ("base", "q5"), ("base", "q9"),
                         ("lora", "q10"), ("lora", "val09"), ("lora", "val38"), ("lora", "val13")}


def main():
    items = {i["item_id"]: i for i in load_items()}
    sims = {}
    for item_id, item in items.items():
        q = np.array(embed_query(item["question"]))
        sims[item_id] = (np.array(embed_texts(item["sources"])) @ q).round(4).tolist()

    rows = []
    for v in map(json.loads, VERIFICATION_PATH.open(encoding="utf-8")):
        item = items[v["item_id"]]
        answer = item["answers"][v["system"]]
        s = sims[v["item_id"]]
        interim = compute_trust_score(answer, [{"similarity": x} for x in s])
        new = compute_claim_trust_score([c["verdict"] for c in v["claims"]],
                                        [bool(c["cited_sources"]) for c in v["claims"]], s, v["is_refusal"])
        rows.append({
            "item_id": v["item_id"], "system": v["system"], "expect_refusal": v["expect_refusal"],
            "is_refusal": v["is_refusal"], "confirmed_unsupported": (v["system"], v["item_id"]) in CONFIRMED_UNSUPPORTED,
            "interim_score": interim.score, "interim_refusal": interim.is_refusal,
            "score": new.score, "label": new.label, "support": new.support,
            "citation_precision": new.citation_precision, "retrieval_relevance": new.retrieval_relevance,
            "num_claims": new.num_claims, "num_flagged": new.num_flagged, "cap_applied": new.cap_applied,
        })

    with OUT_PATH.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")

    def avg(rs, key):
        return f"{mean(r[key] for r in rs):.1f}" if rs else "-"

    lines = ["# Trust Score Evaluation (Phase 10)", "",
             "Auto-generated by `scripts/evaluate_trust_score.py` from the Phase 9 verdicts; overwritten on each run.",
             "Scores are heuristics (\"Trust Score: N/100\"), not probabilities.", "",
             "## Mean score by group", "",
             "| Group | n | Interim | Claim-based |", "|---|---|---|---|"]
    for system in ("base", "lora"):
        rs = [r for r in rows if r["system"] == system]
        answered = [r for r in rs if not r["is_refusal"]]
        groups = {
            f"{system}: answered, no confirmed unsupported claim": [r for r in answered if not r["confirmed_unsupported"]],
            f"{system}: answered, confirmed unsupported claim": [r for r in answered if r["confirmed_unsupported"]],
            f"{system}: correct refusal": [r for r in rs if r["is_refusal"] and r["expect_refusal"]],
            f"{system}: answered a should-refuse question": [r for r in rs if not r["is_refusal"] and r["expect_refusal"]],
            f"{system}: refused an answerable question": [r for r in rs if r["is_refusal"] and not r["expect_refusal"]],
        }
        for name, g in groups.items():
            lines.append(f"| {name} | {len(g)} | {avg(g, 'interim_score')} | {avg(g, 'score')} |")

    answered = [r for r in rows if not r["is_refusal"]]
    lines += ["", "## Label distribution (answered questions)", "",
              "| System | High | Moderate | Low | Capped |", "|---|---|---|---|---|"]
    for system in ("base", "lora"):
        rs = [r for r in answered if r["system"] == system]
        lines.append(f"| {system} | " + " | ".join(str(sum(r["label"] == l for r in rs)) for l in ("High", "Moderate", "Low"))
                     + f" | {sum(r['cap_applied'] is not None for r in rs)} |")

    bad = [r for r in answered if r["confirmed_unsupported"]]
    lines += ["", "## Answers with a confirmed unsupported claim", "",
              "| Item | System | Interim | Claim-based | Flagged claims |", "|---|---|---|---|---|"]
    for r in bad:
        lines.append(f"| {r['item_id']} | {r['system']} | {r['interim_score']} | {r['score']} ({r['label']}) | {r['num_flagged']}/{r['num_claims']} |")

    interim_false_refusals = sum(r["interim_refusal"] and not r["is_refusal"] for r in rows)
    lines += ["", f"Interim `REFUSAL_RE` treated {interim_false_refusals} cited answers as refusals; "
              "the claim-based score uses `is_refusal_answer` (refusal phrase and no citations)."]
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
